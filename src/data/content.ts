export function getLevelByXP(xp: number): Level {
  return LEVELS.find(l => xp >= l.min_xp && xp <= l.max_xp) ?? LEVELS[0];
}

export function getXPProgressPercentage(xp: number): number {
  const level = getLevelByXP(xp);
  if (level.max_xp === Infinity) return 100;
  const range = level.max_xp - level.min_xp;
  const progress = xp - level.min_xp;
  return Math.round((progress / range) * 100);
}

export function getCategoryById(id: string): Category | undefined {
  return CATEGORIES.find(c => c.id === id);
}

export function getQuestionsByCategory(categoryId: string): Question[] {
  return QUESTIONS.filter(q => q.category_id === categoryId && q.is_active);
}

export function getTotalMaxDailyPoints(): number {
  return QUESTIONS.filter(q => q.type === 'daily').reduce((acc, q) => acc + q.points, 0);
}
